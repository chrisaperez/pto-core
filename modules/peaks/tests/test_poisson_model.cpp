void test_batch_indexing_stays_inside_the_log_factorial_table() {
  // A vector gather indexed by the count itself reads out of bounds for any
  // k past the table, and reads a plausible double while doing it. This case
  // exists so the sanitizer build has something to catch: every entry is a
  // count on one side or the other of the boundary, and one is 2^32-1.
  std::vector<std::uint32_t> ks;
  std::vector<double> lams;
  for (std::uint32_t k = 500; k <= 530; ++k) {
    ks.push_back(k);
    lams.push_back(100.0);
  }
  for (std::uint32_t k : {65535u, 65536u, 1000000u, 2147483647u, 4294967295u}) {
    ks.push_back(k);
    lams.push_back(1e6);
  }
  std::vector<double> got(ks.size(), 0.0);
  for (IsaLevel isa : kAllIsas) {
    if (!pto::peaks::isa_compiled(isa)) continue;
    pto::peaks::log_poisson_sf_batch_isa(isa, ks.data(), lams.data(), got.data(),
                                         ks.size());
    for (std::size_t i = 0; i < ks.size(); ++i) {
      const double want = pto::peaks::log_poisson_sf(ks[i], lams[i]);
      check_near(got[i], want, 2.0 * poisson_tolerance(ks[i], lams[i], want) + 1e-300,
                 "table bounds", __LINE__);
    }
  }
}

