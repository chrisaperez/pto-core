// ===========================================================================
// 1. The elementary kernels: this module's replacements for libm.
//
// They are tested against libm rather than against a golden table because the
// platform's log/exp ARE the reference for a single elementary function -- the
// point of owning them is vectorisation and the absence of a call, not better
// accuracy than the system.
// ===========================================================================

void test_log_kernel_matches_libm() {
  const double points[] = {
      1.0, 2.0, 0.5, 4.0, 1e-300, 1e300, 3.0, 7.0,
      2.718281828459045, 3.141592653589793,
      0.9999999999999999, 1.0000000000000002, 1.4142135623730951,
      0.7071067811865476, 1e-10, 1e10, 1024.0, 1023.999999,
      std::numeric_limits<double>::min(),        // smallest normal
      std::numeric_limits<double>::denorm_min(), // smallest denormal
      5e-324, 2.2250738585072011e-308,           // denormal boundary
      std::numeric_limits<double>::max(),
  };
  for (double x : points) {
    CHECK_REL(pto::peaks::log_approx(x), std::log(x), 4.0 * kEps);
  }

  std::mt19937_64 rng(20260909);
  std::uniform_real_distribution<double> mant(1.0, 2.0);
  std::uniform_int_distribution<int> expo(-1020, 1020);
  for (int i = 0; i < 20000; ++i) {
    const double x = std::ldexp(mant(rng), expo(rng));
    CHECK_REL(pto::peaks::log_approx(x), std::log(x), 4.0 * kEps);
  }

  // Subnormals are their own path: the mantissa cannot be extracted by the
  // usual bit split without first scaling the value into the normal range.
  for (int i = 1; i < 400; ++i) {
    const double x = std::ldexp(1.0, -1074 + i) * 1.5;
    CHECK_REL(pto::peaks::log_approx(x), std::log(x), 4.0 * kEps);
  }

  // Domain edges, which must agree with libm rather than trap.
  CHECK(pto::peaks::log_approx(0.0) == -kInf);
  CHECK(pto::peaks::log_approx(-0.0) == -kInf);
  CHECK(std::isnan(pto::peaks::log_approx(-1.0)));
  CHECK(std::isnan(pto::peaks::log_approx(kNaN)));
  CHECK(pto::peaks::log_approx(kInf) == kInf);
  CHECK(pto::peaks::log_approx(1.0) == 0.0);
}

void test_exp_kernel_matches_libm() {
  const double points[] = {0.0,   1.0,   -1.0,  0.5,   -0.5,   709.0,  -708.0,
                           -745.0, 700.0, 1e-20, -1e-20, 0.3465735902799726,
                           -0.3465735902799726, 100.0, -100.0, 20.0, -20.0};
  for (double x : points) {
    CHECK_REL(pto::peaks::exp_approx(x), std::exp(x), 4.0 * kEps);
  }

  std::mt19937_64 rng(20260910);
  std::uniform_real_distribution<double> u(-700.0, 700.0);
  for (int i = 0; i < 20000; ++i) {
    const double x = u(rng);
    CHECK_REL(pto::peaks::exp_approx(x), std::exp(x), 4.0 * kEps);
  }

  // Gradual underflow: exp(-745) is denormal and exp(-746) is zero. Getting
  // this wrong the other way -- returning a normal number -- would make an
  // impossible p-value look merely small.
  for (double x = -700.0; x > -760.0; x -= 0.5) {
    CHECK_REL(pto::peaks::exp_approx(x), std::exp(x), 1e-10);
  }
  CHECK(pto::peaks::exp_approx(-800.0) == 0.0);
  CHECK(pto::peaks::exp_approx(-kInf) == 0.0);
  CHECK(pto::peaks::exp_approx(800.0) == kInf);
  CHECK(pto::peaks::exp_approx(kInf) == kInf);
  CHECK(std::isnan(pto::peaks::exp_approx(kNaN)));
  CHECK(pto::peaks::exp_approx(0.0) == 1.0);
}

void test_log1p_kernel_matches_libm() {
  // The whole reason log1p exists here: log(1 + y) for tiny y throws the
  // answer away. A p-value of 1 - 3.8e-42 is not the same number as 1.
  const double points[] = {0.0,   1e-300, -1e-300, 1e-17,  -1e-17, 0.5,
                           -0.5,  1.0,    -0.9,    -0.99,  100.0,  1e300,
                           -0.3333333333333333, 0.4142135623730951,
                           -0.2928932188134524};
  for (double y : points) {
    CHECK_REL(pto::peaks::log1p_approx(y), std::log1p(y), 4.0 * kEps);
  }

  std::mt19937_64 rng(20260911);
  std::uniform_real_distribution<double> u(-0.5, 0.5);
  for (int i = 0; i < 20000; ++i) {
    const double y = u(rng);
    CHECK_REL(pto::peaks::log1p_approx(y), std::log1p(y), 4.0 * kEps);
  }
  for (int i = 0; i < 5000; ++i) {
    const double y = -std::ldexp(u(rng) + 0.5, -(i % 200));  // approach -0 and -1
    CHECK_REL(pto::peaks::log1p_approx(y), std::log1p(y), 8.0 * kEps);
  }

  CHECK(pto::peaks::log1p_approx(-1.0) == -kInf);
  CHECK(std::isnan(pto::peaks::log1p_approx(-2.0)));
  CHECK(std::isnan(pto::peaks::log1p_approx(kNaN)));
  CHECK(pto::peaks::log1p_approx(0.0) == 0.0);
}

