void test_log_factorial_matches_golden() {
  for (const auto& g : kFactorialGolden) {
    CHECK_REL(pto::peaks::log_factorial(g.k), g.lf,
              (g.lf == 0.0) ? 0.0 : 8.0 * kEps);
  }
  // 0! and 1! are 1, and their logarithm is a zero this must produce exactly
  // rather than approximately: a peak caller divides by nothing here, but a
  // -0.0 or a 1e-17 propagates into every downstream sum.
  CHECK(pto::peaks::log_factorial(0) == 0.0);
  CHECK(pto::peaks::log_factorial(1) == 0.0);
}

void test_log_factorial_matches_libm_over_the_table_and_past_it() {
  for (std::uint32_t k = 0; k <= 4000; ++k) {
    const double ref = std::lgamma(static_cast<double>(k) + 1.0);
    CHECK_REL(pto::peaks::log_factorial(k), ref, (ref == 0.0) ? 0.0 : 8.0 * kEps);
  }
  for (std::uint32_t k : {100000u, 1000000u, 16777216u, 2147483647u, 4294967295u}) {
    CHECK_REL(pto::peaks::log_factorial(k), std::lgamma(static_cast<double>(k) + 1.0),
              8.0 * kEps);
  }
}

void test_log_factorial_table_seam_is_continuous() {
  // The table ends at kLogFactorialTableMax and the Stirling series takes over
  // on the next index. A discontinuity there would be invisible in any single
  // value and would show up as a step in the p-value track at one pileup depth.
  const std::uint32_t m = pto::peaks::kLogFactorialTableMax;
  for (std::uint32_t k = m - 3; k <= m + 3; ++k) {
    const double ours = pto::peaks::log_factorial(k);
    const double ref = std::lgamma(static_cast<double>(k) + 1.0);
    CHECK_REL(ours, ref, 8.0 * kEps);
    // ln(k!) - ln((k-1)!) is exactly ln(k), across the seam as anywhere else.
    if (k > 0) {
      const double step = ours - pto::peaks::log_factorial(k - 1);
      CHECK_REL(step, std::log(static_cast<double>(k)), 1e-13);
    }
  }
}

void test_lgamma_matches_golden() {
  for (const auto& g : kLgammaGolden) {
    // lnGamma has zeros at 1 and 2, so relative accuracy is not a meaningful
    // demand in their neighbourhood -- the absolute floor covers it, and the
    // Poisson path never evaluates a non-integer argument anyway.
    check_near(pto::peaks::lgamma_approx(g.z), g.lg,
               std::fabs(g.lg) * 16.0 * kEps + 1e-13, "lgamma_approx golden",
               __LINE__);
  }
  CHECK(pto::peaks::lgamma_approx(1.0) == 0.0);
  CHECK(pto::peaks::lgamma_approx(2.0) == 0.0);
}

void test_lgamma_matches_libm_sweep() {
  std::mt19937_64 rng(20260912);
  std::uniform_real_distribution<double> small(1e-6, 16.0);
  for (int i = 0; i < 20000; ++i) {
    const double z = small(rng);
    check_near(pto::peaks::lgamma_approx(z), std::lgamma(z),
               std::fabs(std::lgamma(z)) * 16.0 * kEps + 1e-13, "lgamma small",
               __LINE__);
  }
  std::uniform_real_distribution<double> big(16.0, 1e8);
  for (int i = 0; i < 20000; ++i) {
    const double z = big(rng);
    CHECK_REL(pto::peaks::lgamma_approx(z), std::lgamma(z), 16.0 * kEps);
  }
}

void test_lgamma_guards_its_domain() {
  // The poles. Returning something finite here is the dangerous direction:
  // `lead` subtracts lnGamma, so a finite wrong value at a pole becomes a
  // finite wrong p-value instead of an obviously absent one.
  CHECK(pto::peaks::lgamma_approx(0.0) == kInf);
  CHECK(pto::peaks::lgamma_approx(-0.0) == kInf);
  CHECK(pto::peaks::lgamma_approx(-1.0) == kInf);
  CHECK(pto::peaks::lgamma_approx(-2.0) == kInf);
  CHECK(pto::peaks::lgamma_approx(-1e300) == kInf);
  // Negative non-integers are outside the supported domain and are reported as
  // absent rather than reflected: nothing in a peak caller has one.
  CHECK(pto::peaks::lgamma_approx(-0.5) == kInf);
  CHECK(std::isnan(pto::peaks::lgamma_approx(kNaN)));
  CHECK(pto::peaks::lgamma_approx(kInf) == kInf);
  // Denormal and tiny arguments: lnGamma(z) ~ -ln(z) as z -> 0.
  CHECK_REL(pto::peaks::lgamma_approx(1e-300), std::lgamma(1e-300), 1e-13);
  CHECK_REL(pto::peaks::lgamma_approx(5e-324), std::lgamma(5e-324), 1e-13);
}

