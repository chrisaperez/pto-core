void test_no_scalar_libm_calls_in_the_header() {
  // Every transcendental in this header is open-coded so that the vector
  // kernels have something to vectorise: there is no libm call that takes a
  // __m256d, and a scalar log() inside a per-position loop costs more than
  // everything around it. That property is a fact about the source, not about
  // any output value, so this is where it is checked -- the same argument
  // scrna_matrix's test_no_bare_float_accumulators makes.
  //
  // Classification (isfinite/isnan) and fabs are not on the list: they compile
  // to a test or a bit mask, not a call.
  const std::filesystem::path header =
      std::filesystem::path(PTO_PEAKS_SOURCE_DIR) / "include" / "peaks" / "poisson_model.hpp";
  std::ifstream in(header);
  if (!in) {
    // A guard that silently scans zero files reads as coverage. It is not.
    std::fprintf(stderr, "  FAIL cannot open %s for the libm scan\n",
                 header.string().c_str());
    ++g_failures;
    ++g_checks;
    return;
  }

  std::string src, line;
  std::size_t lineno = 0;
  std::vector<std::pair<std::size_t, std::string>> lines;
  while (std::getline(in, line)) {
    ++lineno;
    // Prose is allowed to name the functions it bans.
    const std::size_t comment = line.find("//");
    if (comment != std::string::npos) line.erase(comment);
    lines.emplace_back(lineno, line);
  }
  CHECK(lines.size() > 200);  // the scan ran over something

  const std::regex banned(
      R"((^|[^A-Za-z0-9_.>])(std::)?)"
      R"((log|log2|log10|log1p|logb|exp|exp2|expm1|pow|lgamma|tgamma|erf|erfc|)"
      R"(sin|cos|tan|atan|atan2|sinh|cosh|tanh|asinh|acosh|atanh|cbrt|hypot|)"
      R"(floor|ceil|round|rint|nearbyint|trunc|frexp|ldexp|scalbn|modf)f?)"
      R"(\s*\()");
  for (const auto& [no, text] : lines) {
    std::smatch m;
    if (std::regex_search(text, m, banned)) {
      report(false, "libm call in a hot path", __LINE__,
             header.filename().string() + ":" + std::to_string(no) + ": " + m.str());
    } else {
      ++g_checks;
    }
  }
}

