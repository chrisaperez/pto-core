// pto-peaks: the Poisson survival function and its SIMD log-gamma core.
//
// This is the module's numerical contract. Everything downstream of it -- the
// Benjamini-Hochberg pass, the summit scores, the narrowPeak q-value column --
// is a monotone transform of what `log_poisson_sf` returns, so an error here
// does not produce a visibly broken peak call. It produces a plausible one.
// That is the reason this suite is as large as it is.
//
// Four kinds of check, and the distinction matters when one of them fails:
//
//   1. GOLDEN VALUES.  ln P(X >= k) at 80 significant digits from mpmath's
//      regularised incomplete gamma -- a different algorithm, a different
//      arithmetic, and not derived from this header. Generated by
//      scripts/gen_poisson_golden.py; see that file to add cases.
//   2. CLOSED FORMS.  P(X >= 1) = 1 - e^-lam and P(X >= 2) = 1 - e^-lam(1+lam)
//      are exact algebra, so they pin small k independently of any table.
//   3. STRUCTURAL PROPERTIES.  Monotone in k, monotone in lam, always finite,
//      never positive, fail-closed on a degenerate lambda. These hold for
//      every input, including the ones no golden table would think to list.
//   4. SIMD/SCALAR PARITY.  Every kernel compiled into this binary, driven
//      explicitly through `*_batch_isa` rather than through whatever the host
//      CPU happens to dispatch to -- one machine exercises every path.
//
// The tolerances are derived, not tuned. `poisson_tolerance()` carries the
// error model and the reason it differs between the two branches; read it
// before loosening anything.
